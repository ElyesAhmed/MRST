    '90 if (TC<=10) then rate = 0\n' ...
    '100 if (TC>=113) then rate = 0\n' ...
    '101 TDS = (RHO - TOT("water")/SOLN_VOL)*1e3\n' ...
    '102 if (TDS>=50) then rate = rate * (TDS-2*50+300)*(300-TDS)/(300-50)^2\n' ...
    '103 if (TDS>300) then rate = 0\n' ...
    '110 put(rate,2)\n' ...
    '120 moles = rate*TIME\n' ...
    '200 SAVE moles\n' ...
    '-end\n' ...
    'ACE\n' ...
    '-start\n' ...
    '20 rate = %.15g/86400/%.15g*kin("Biomass_ACE")*mol("H2")/(%.15g+mol("H2"))*tot("Carbonate(4)")/(%.15g+tot("Carbonate(4)"))\n' ...
    '30 if (TC<38) then rate = -rate * (TC-25)*(TC+25-2*38)/(38-25)^2\n' ...
    '40 if (TC>=38) then rate = -rate * (TC-72)*(TC+72-2*38)/(72-38)^2\n' ...
    '50 if (-LA("H+")<7.04) then rate = -rate * (-LA("H+")-3.6)*(-LA("H+")+3.6-2*7.04)/(7.04-3.6)^2\n' ...
    '60 if (-LA("H+")>=7.04) then rate = -rate * (-LA("H+")-9.5)*(-LA("H+")+9.5-2*7.04)/(7.04-9.5)^2\n' ...
    '70 if (-LA("H+")>=9.5) then rate = 0\n' ...
    '80 if (-LA("H+")<=3.6) then rate = 0\n' ...
    '90 if (TC<=25) then rate = 0\n' ...
