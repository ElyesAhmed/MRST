waterIndex = findComponent(names, {'H2O', 'Water'});
assert(~isempty(waterIndex), 'UGFACT PHREEQC requires the EOS H2O component.');
waterMolarMass = model.EOSModel.CompositionalMixture.molarMass(waterIndex);
