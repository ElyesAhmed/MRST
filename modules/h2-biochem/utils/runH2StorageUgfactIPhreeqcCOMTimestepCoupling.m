biomassACE = state.phreeqcUgfactBiomassACE(cellNo);
biomassSRB = state.phreeqcUgfactBiomassSRB(cellNo);
maxBiomass = opt.ugfactNmax*opt.ugfactCellMass/opt.ugfactBiomassMW;
minBiomass = opt.ugfactN0*opt.ugfactCellMass/opt.ugfactBiomassMW;
if phase.activeCells(cellNo)
    h2Available = max(phase.totalH2(cellNo)./phase.waterMass(cellNo), 0);
else
    h2Available = 0;
end

input = sprintf([ ...
    'KNOBS\n' ...
    '-iterations 800\n' ...
    '-step_size 30\n' ...
    '-convergence_tolerance 1e-10\n' ...
    '%s' ...
    'END\n' ...
