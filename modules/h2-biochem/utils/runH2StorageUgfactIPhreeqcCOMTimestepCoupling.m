    'RATES\n' ...
    'MET\n' ...
    '-start\n' ...
    '20 rate = %.15g/86400/%.15g*kin("Biomass_MET")*mol("H2")/(%.15g+mol("H2"))*tot("Carbonate(4)")/(%.15g+tot("Carbonate(4)"))\n' ...
    '30 if (TC<45) then rate = -rate * (TC-10)*(TC+10-2*45)/(45-10)^2\n' ...
    '40 if (TC>=45) then rate = -rate * (TC-122)*(TC+122-2*45)/(45-122)^2\n' ...
    '50 if (-LA("H+")<7.7) then rate = -rate * (-LA("H+")-4.1)*(-LA("H+")+4.1-2*7.7)/(7.7-4.1)^2\n' ...
    '60 if (-LA("H+")>=7.7) then rate = -rate * (-LA("H+")-10.2)*(-LA("H+")+10.2-2*7.7)/(7.7-10.2)^2\n' ...
    '70 if (-LA("H+")>=10.2) then rate = 0\n' ...
    '80 if (-LA("H+")<=4.1) then rate = 0\n' ...
    '90 if (TC<=10) then rate = 0\n' ...
    '100 if (TC>=122) then rate = 0\n' ...
    '101 TDS = (RHO - TOT("water")/SOLN_VOL)*1e3\n' ...
    '102 if (TDS>=50) then rate = rate * (TDS-2*50+300)*(300-TDS)/(300-50)^2\n' ...
    '103 if (TDS>300) then rate = 0\n' ...
