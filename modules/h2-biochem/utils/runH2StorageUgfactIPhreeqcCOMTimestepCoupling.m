state.phreeqcMineralPyrite = max(reshape([result.pyrite], [], 1), 0).*waterMass;
state.phreeqcMineralGypsum = max(reshape([result.gypsum], [], 1), 0).*waterMass;

biomassMET = max(reshape([result.biomassMET], [], 1), 0);
biomassACE = max(reshape([result.biomassACE], [], 1), 0);
biomassSRB = max(reshape([result.biomassSRB], [], 1), 0);
biomassMET(inactive) = state.phreeqcUgfactBiomassMET(inactive);
biomassACE(inactive) = state.phreeqcUgfactBiomassACE(inactive);
biomassSRB(inactive) = state.phreeqcUgfactBiomassSRB(inactive);
state.phreeqcUgfactBiomassMET = biomassMET;
state.phreeqcUgfactBiomassACE = biomassACE;
state.phreeqcUgfactBiomassSRB = biomassSRB;
reactionRates = [reshape([result.rateMET], [], 1), ...
    reshape([result.rateACE], [], 1), reshape([result.rateSRB], [], 1)];
reactionRates(inactive, :) = 0;
state.phreeqcUgfactReactionRates = reactionRates;
state.phreeqcUgfactActiveCells = phase.activeCells;
state.phreeqcUgfactH2ConsumptionByReactionRate = reactionRates.*waterMass;
state.phreeqcUgfactH2ConsumptionByReactionMoles = ...
    state.phreeqcUgfactH2ConsumptionByReactionRate.*dt;
state.phreeqcUgfactH2ConsumptionRate = sum(reactionRates, 2).*waterMass;
state.phreeqcUgfactH2ConsumptionMoles = ...
    state.phreeqcUgfactH2ConsumptionRate.*dt;
