function output = runIPhreeqcCOM(input, opt, cellNo)
try
    iph = actxserver(char(opt.comProgId));
catch ME
    error('H2Biochem:UGFACTCOMActivation', ...
        'IPhreeqcCOM activation failed in cell %d for "%s":\n%s', ...
        cellNo, char(opt.comProgId), ME.message);
end
try
    loadStatus = iph.LoadDatabase(char(opt.databaseFile));
    if loadStatus ~= 0
        error('H2Biochem:UGFACTCOMDatabase', ...
            'PHREEQC database load failed in cell %d:\n%s', cellNo, ...
            getPhreeqcError(iph));
    end
    status = iph.RunString(input);
    if status ~= 0
        error('H2Biochem:UGFACTCOMRun', ...
            'PHREEQC failed in cell %d:\n%s', cellNo, getPhreeqcError(iph));
    end
    output = iph.GetSelectedOutputArray;
    if isempty(output)
        error('H2Biochem:UGFACTCOMOutput', ...
            'PHREEQC returned no selected output in cell %d:\n%s', ...
            cellNo, getPhreeqcError(iph));
    end
catch ME
    phreeqcMessage = getPhreeqcError(iph);
    try
        clear iph
    catch
    end
    if startsWith(ME.identifier, 'H2Biochem:UGFACTCOM')
        rethrow(ME);
    end
    error('H2Biochem:UGFACTCOMRun', ...
        'IPhreeqcCOM failed in cell %d:\n%s\nPHREEQC message:\n%s', ...
        cellNo, ME.message, phreeqcMessage);
end
clear iph
end

function message = getPhreeqcError(iph)
try
    message = char(iph.GetErrorString());
catch
    message = 'No PHREEQC error string was available from IPhreeqcCOM.';
end
if isempty(strtrim(message))
    message = 'IPhreeqcCOM did not provide an error message.';
end
end

