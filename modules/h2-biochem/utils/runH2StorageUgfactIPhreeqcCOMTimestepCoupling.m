    {'gredoxcarbonateo2g', 'redoxcarbonateo2g'}, cellNo);
result.gasCH4 = finalValue(values, headers, {'gredoxch4g', 'redoxch4g'}, cellNo);
result.gasH2S = finalValue(values, headers, {'gredoxh2sg', 'redoxh2sg'}, cellNo);
result.gasN2 = finalValue(values, headers, {'gn2g', 'n2g'}, cellNo);
result.calcite = finalValue(values, headers, {'redoxcalcite'}, cellNo);
result.anhydrite = finalValue(values, headers, {'redoxanhydrite'}, cellNo);
result.gypsum = finalValue(values, headers, {'redoxgypsum'}, cellNo);
result.dolomite = finalValue(values, headers, {'redoxdolomite'}, cellNo);
result.goethite = finalValue(values, headers, {'redoxgoethite'}, cellNo);
