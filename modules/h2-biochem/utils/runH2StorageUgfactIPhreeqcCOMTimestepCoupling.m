function state = runH2StorageUgfactIPhreeqcCOMTimestepCoupling(model, state, dt)
% Run the optional UGFACT PHREEQC_Modified.DAT split after convergence.
%
% This backend intentionally follows the UGFACT IPhreeqcCOM input and
% SELECTED_OUTPUT convention. It is Windows-only: PHREEQC owns MET/ACE/SRB
% kinetics and its biomass state, while MRST retains flow and tracer
% transport. It is a sequential split, not a claim of exact reproduction
% of any external benchmark or publication.

assert(model.phreeqcTimestepCoupling && model.isUgfactComPhreeqcBackend(), ...
    'UGFACT IPhreeqcCOM timestep coupling is not enabled on this model.');
assert(ispc, ['UGFACT IPhreeqcCOM timestep coupling is available only on ', ...
    'Windows with a registered IPhreeqcCOM server.']);
validateattributes(dt, {'numeric'}, {'scalar', 'real', 'finite', 'positive'}, ...
    mfilename, 'dt');

opt = getCouplingOptions(model);
validateCouplingOptions(opt);
assert(exist('actxserver', 'file') == 2 || exist('actxserver', 'builtin') == 5, ...
    ['IPhreeqcCOM activation is unavailable. Install/register the Windows ', ...
     'IPhreeqcCOM server identified by phreeqcComProgId.']);

nc = model.G.cells.num;
rhoWater = opt.waterDensity;
waterMass = getWaterMass(model, state, rhoWater);
assert(all(isfinite(waterMass) & waterMass > 0), ...
    'UGFACT PHREEQC coupling requires positive liquid water mass in every cell.');

state = initializeUgfactState(state, opt, nc);
state = applyUgfactFirstStepBiomassConvention(state, waterMass);
phase = getPhaseData(model, state, waterMass, rhoWater);
mineral = getMineralData(state, waterMass, nc);
state = storePhreeqcInputDiagnostics(state, phase);

results = repmat(emptyResult(), nc, 1);
for cellNo = 1:nc
    input = buildPhreeqcInput(opt, phase, mineral, state, cellNo, dt);
    if cellNo == 1
        state.phreeqcUgfactInputCell1String = input;
    end
    output = runIPhreeqcCOM(input, opt, cellNo);
    results(cellNo) = parseSelectedOutput(output, cellNo);
end

state = updateStateFromResults(model, state, opt, phase, mineral, results, waterMass, dt);
end

function state = storePhreeqcInputDiagnostics(state, phase)
% Retain the exact mol/kg-water PHREEQC basis for comparison with UGFACT.
state.phreeqcUgfactInputWaterMass = phase.waterMass;
state.phreeqcUgfactInputH2Moles = phase.gasH2;
state.phreeqcUgfactInputCO2Moles = phase.gasCO2;
state.phreeqcUgfactInputCH4Moles = phase.gasCH4;
state.phreeqcUgfactInputH2SMoles = phase.gasH2S;
state.phreeqcUgfactInputGasVolumeLPerKg = phase.gasVolumeLPerKg;
state.phreeqcUgfactInputPH = phase.pH;
state.phreeqcUgfactInputC4 = phase.C4;
state.phreeqcUgfactInputS6 = phase.S6;
state.phreeqcUgfactInputCa = phase.Ca;
state.phreeqcUgfactInputMg = phase.Mg;
state.phreeqcUgfactInputActiveCells = phase.activeCells;
end

