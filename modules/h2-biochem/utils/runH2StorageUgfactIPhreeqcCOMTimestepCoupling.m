    '-type 1\n' ...
    '-total_p %.15g\n' ...
    '-volume %.15g\n' ...
    '-component H2(g)\n' ...
    '-moles %.15g\n' ...
    '-component redoxCH4(g)\n' ...
    '-moles %.15g\n' ...
    '-component redoxCarbonateO2(g)\n' ...
    '-moles %.15g\n' ...
    '-component redoxH2S(g)\n' ...
    '-moles %.15g\n' ...
    '-component N2(g)\n' ...
    '-moles %.15g\n' ...
    'END\n' ...
    'INCREMENTAL_REACTIONS true\n' ...
    'KINETICS 1\n' ...
    'Biomass_SRB\n' ...
    '-formula H 0\n' ...
    '-M0 %.15g\n' ...
    'Biomass_MET\n' ...
    '-formula H 0\n' ...
    '-M0 %.15g\n' ...
    'Biomass_ACE\n' ...
    '-formula H 0\n' ...
    '-M0 %.15g\n' ...
    'MET\n' ...
    '-M %.15g moles\n' ...
    '-formula HCarbonateO3 -0.25 H2 -1 H+ -0.25 MethaneH4 0.25 H2O 0.75\n' ...
    'SRB\n' ...
    '-M %.15g moles\n' ...
    '-formula SulfateO4 -0.25 H2 -1 H+ -0.25 HSulfide 0.25 H2O 1\n' ...
    'ACE\n' ...
    '-M %.15g moles\n' ...
    '-formula HCarbonateO3 -0.5 H2 -1 H+ -0.25 Acetate 0.25 H2O 1\n' ...
    '-step %.15g in %d steps\n' ...
    '-bad_step_max 800\n' ...
    'END\n' ...
    'EQUILIBRIUM_PHASES 1\n' ...
    'redoxCalcite 0 %.15g\n' ...
    'redoxDolomite 0 %.15g\n' ...
    'redoxAnhydrite 0 %.15g\n' ...
    'Quartz 0 %.15g\n' ...
    'redoxGoethite 0 %.15g\n' ...
    'redoxPyrite 0 %.15g\n' ...
    'Brucite 0 %.15g\n' ...
    'Portlandite 0 %.15g\n' ...
    'redoxGypsum 0 %.15g\n' ...
    'END\n' ...
    'USE solution 1\n' ...
    'USE kinetics 1\n' ...
    'USE equilibrium_phases 1\n' ...
    'USE gas_phase 1\n' ...
    '%s'], ...
    buildRates(opt, minBiomass, maxBiomass), ...
    phase.pressureAtm(cellNo), phase.temperature(cellNo) - 273.15, phase.pH(cellNo), ...
    phase.K(cellNo), phase.Na(cellNo), phase.Mg(cellNo), phase.Ca(cellNo), ...
    phase.Cl(cellNo), phase.C4(cellNo), phase.S6(cellNo), phase.S2(cellNo), ...
    phase.Fe3(cellNo), phase.Fe2(cellNo), phase.Si(cellNo), phase.Acetate(cellNo), ...
